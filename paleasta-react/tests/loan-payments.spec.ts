import { test,expect } from "@playwright/test";
import { createDemoState } from "../src/demo-data";
test("separate loan payment dialog selects a loan, saves its split, and handles payoff",async({page})=>{
 let business:any;
 await page.route("**/api/chat",async route=>{business=route.request().postDataJSON().business;await route.fulfill({json:{html:"<p>Your payment is recorded.</p>"}});});
 await page.goto("/#/app/transactions");
 await page.getByRole("button",{name:"Add business loan",exact:true}).click();
 await expect(page.getByRole("dialog",{name:"Record business loan"})).toBeVisible();
 await page.keyboard.press("Escape");
 const open=page.getByRole("button",{name:"Record loan payment",exact:true});
 await open.click();
 const dialog=page.getByRole("dialog",{name:"Record loan payment"});
 await expect(dialog).toBeVisible();
 await expect(dialog.getByRole("button",{name:"Close",exact:true})).toHaveCount(0);
 await dialog.getByLabel("Business loan", {exact:true}).selectOption("sample-loan-working-2026");
 await expect(dialog.getByLabel("Business loan",{exact:true}).locator("option:checked")).toContainText("15,000");
 await dialog.getByLabel("Business loan",{exact:true}).selectOption("sample-loan-coop-2026");
 await dialog.getByLabel("Principal paid (PHP)").fill("3000");
 await dialog.getByLabel("Interest / fees paid (PHP)").fill("500");
 await dialog.getByLabel("Payment date",{exact:true}).fill("2026-10-27");
 await dialog.getByLabel("Next payment due (from lender)").fill("2026-11-30");
 await expect(dialog).toContainText("₱3,500.00");
 await expect(dialog).toContainText("₱27,000.00");
 expect(await dialog.getByRole("button",{name:"Save loan payment",exact:true}).evaluate(el=>getComputedStyle(el).backgroundColor)).toBe("rgb(181, 68, 54)");
 await dialog.screenshot({path:"test-results/loan-payment-modal.png",animations:"disabled"});
 await dialog.getByRole("button",{name:"Save loan payment",exact:true}).click();
 await expect(dialog).toHaveCount(0);
 await expect(page.getByRole("row").filter({hasText:"Loan payment · Sample cooperative loan"})).toContainText("Cash outflow · loan payment");
 let saved=await page.evaluate(()=>JSON.parse(localStorage.getItem("paleasta-prototype-v1")!));
 expect(saved.transactions[0]).toMatchObject({cashKind:"loan_repayment",amountCents:350000,loanPayment:{principalCents:300000,interestCents:50000}});
 expect(saved.loans[0]).toMatchObject({outstandingCents:2700000,nextDueDate:"2026-11-30"});
 await page.reload();await open.click();
 await dialog.getByLabel("Principal paid (PHP)").fill("27000");
 await dialog.getByLabel("Payment date",{exact:true}).fill("2026-10-27");
 await expect(dialog.getByLabel("Next payment due (from lender)")).toHaveCount(0);
 await expect(dialog).toContainText("marked paid off");
 await dialog.getByRole("button",{name:"Save loan payment",exact:true}).click();
 saved=await page.evaluate(()=>JSON.parse(localStorage.getItem("paleasta-prototype-v1")!));
 expect(saved.loans[0]).toMatchObject({outstandingCents:0,status:"paid"});
 await open.click();
 await expect(dialog.getByLabel("Business loan",{exact:true}).locator("option")).toHaveCount(1);
 await page.keyboard.press("Escape");
 await page.goto("/#/app/adviser");
 await page.getByLabel("Your question or business goal").fill("Review my loan payments");
 await page.getByRole("button",{name:"Send message",exact:true}).click();
 await expect(page.locator(".lea-answer")).toBeVisible();
 expect(business.transactions[0].loanPayment).toEqual({principalCents:2700000,interestCents:0});
 expect(business.loans[0].status).toBe("paid");
});
test("no-loan state leads to the loan dialog, and payment validation preserves records",async({page})=>{
 await page.goto("/");
 await page.evaluate(seed=>localStorage.setItem("paleasta-prototype-v1",JSON.stringify({...seed,loans:[]})),createDemoState());
 await page.goto("/#/app/transactions");await page.reload();
 await page.getByRole("button",{name:"Record loan payment",exact:true}).click();
 let dialog=page.getByRole("dialog",{name:"Record loan payment"});
 await expect(dialog).toContainText("No outstanding loan");
 await dialog.getByRole("button",{name:"Add business loan",exact:true}).click();
 await expect(page.getByRole("dialog",{name:"Record business loan"})).toBeVisible();
 await page.keyboard.press("Escape");
 await page.evaluate(seed=>localStorage.setItem("paleasta-prototype-v1",JSON.stringify(seed)),createDemoState());await page.reload();
 await page.getByRole("button",{name:"Record loan payment",exact:true}).click();
 dialog=page.getByRole("dialog",{name:"Record loan payment"});
 await dialog.getByLabel("Principal paid (PHP)").fill("31000");
 await dialog.getByLabel("Payment date",{exact:true}).fill("2026-10-27");
 await dialog.getByLabel("Next payment due (from lender)").fill("2026-11-30");
 await dialog.getByRole("button",{name:"Save loan payment",exact:true}).click();
 await expect(dialog.getByRole("alert")).toContainText("cannot exceed");
 expect(await page.evaluate(()=>JSON.parse(localStorage.getItem("paleasta-prototype-v1")!).transactions.length)).toBe(317);
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(1);
 await page.keyboard.press("Escape");
 await expect(page.getByRole("dialog")).toHaveCount(0);
});

